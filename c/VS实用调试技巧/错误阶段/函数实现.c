/*
 * 用途：返回两个整数的和。
 * 参数：left、right 是 int；调用者须保证数学和可由 int 表示。
 * 返回值：left + right。
 * 异常/错误：C 不使用异常；不检查溢出，超出 int 可表示范围不在本示例的有效输入内。
 * 副作用：无。
 * 复杂度：时间 O(1)，辅助空间 O(1)。
 * 用法：调用方.c 以 add_two_integers(12, 30) 调用，得到 42。
 */
int add_two_integers(int left, int right)
{
    return left + right;
}
