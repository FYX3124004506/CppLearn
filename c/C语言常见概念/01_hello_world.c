/*
 * 文件用途：演示一个最小的 C 程序，以及 main、标准输出和退出状态。
 * 输入：无；程序不读取命令行参数或标准输入。
 * 输出：向标准输出写入一行 Hello, World!。
 */
#include <stdio.h>

/*
 * 用途：程序入口，输出固定的问候语并以正常状态结束。
 * 参数：无；void 明确表示不接收参数。
 * 返回值：int；返回 0 表示正常结束。
 * 异常/错误：C 不使用异常机制；本函数没有输入要校验，固定返回 0。printf 的写出错误未检查，也没有另一个错误码。
 * 副作用：向标准输出写入一行文本。
 * 复杂度：时间 O(1)，辅助空间 O(1)；仅输出固定长度字符串。
 * 示例：程序运行环境调用 main；执行本文件生成的程序后输出 Hello, World!。
 */
int main(void) {
    // main 是 C 程序的执行入口；标准形式明确返回 int 且不接收参数。
    printf("Hello, World!\n");  // \n 表示换行。

    // 返回 0 表示程序正常结束。
    return 0;
}
