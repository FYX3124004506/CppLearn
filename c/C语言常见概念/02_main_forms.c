/*
 * 文件用途：比较标准 main 形式与若干仅供阅读的旧式/非标准写法。
 * 输入：无；只有当前未注释的 main 会执行，不读取启动参数。
 * 输出：标准输出显示当前实际编译的 main 形式；其余形式仍是注释示例。
 */
#include <stdio.h>

/*
 * 推荐写法：int main(void)
 * void 明确表示函数不接收参数，int 表示向操作系统返回状态码。
 *
 * 用途：唯一实际编译的程序入口，打印标准 main 写法说明。
 * 参数：无；void 表示不接收命令行参数。
 * 返回值：int；返回 0 表示正常结束。
 * 异常/错误：C 不使用异常机制；没有输入校验；printf 写出错误未检查，程序仍返回 0。
 * 副作用：向标准输出写入一行文本。
 * 复杂度：时间 O(1)，辅助空间 O(1)；只输出固定字符串。
 * 示例：运行本文件对应的程序，实际调用该 main 并打印标准写法说明；注释中的其他 main 不参与调用。
 */
int main(void) {
    printf("标准写法：int main(void)\n");
    return 0;
}

