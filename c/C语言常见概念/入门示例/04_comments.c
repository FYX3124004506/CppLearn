/*
 * 文件用途：展示单行注释、块注释、字符串中的注释符和块注释不能嵌套。
 * 输入：无；计数初值在 main 中固定。
 * 输出：显示计数结果和普通文本。
 * 标准：C99 或更新版本。
 */
#include <stdio.h> /* 引入 printf 的声明，以便输出计数和字符串。 */

/*
 * 受控编译反例（以下行保持为 // 注释，完整程序因此仍可编译）：
 * 如果移除每行开头的 //，第一个块注释结束标记会先关闭外层注释，后续残留源码会产生诊断。
 */
// /* outer comment begins
//    /* inner-looking comment */ int = 3;

/*
 * 用途：修改局部计数并展示注释符放在字符串中只是普通文本。
 * 参数：无；示例不读取输入。
 * 返回值：int；返回 0 表示正常结束。
 * 错误处理：没有输入要校验；printf 写出错误未检查。
 * 副作用：改变局部 count，并向标准输出写入两行。
 */
int main(void) {
    int count = 2; /* 声明并初始化计数器，作为后续加法的起点。 */
    count += 3; /* 复合赋值把 3 加到 count 上，等价于 count = count + 3。 */
    printf("count = %d\n", count); /* %d 匹配 int；显示加法后的 5。 */
    printf("// and /* */ inside a string are text\n"); /* 引号内的注释符是字符串字符，不会开始或结束源码注释。 */
    return 0; /* 结束 main 并报告正常结束。 */
}

// 示例输入：无；count 固定从 2 开始。
// 预期输出：
// count = 5
// // and /* */ inside a string are text
// 预期编译结论：活动代码应正常编译；上方注释中的嵌套块注释反例若去掉行注释保护，会产生编译诊断，具体文字依实现而异。
// 关键结果：注释帮助解释源码但不会运行；字符串里的相同字符会按普通文本输出。
