/*
 * 文件用途：展示换行、水平制表、引号和反斜杠转义序列。
 * 输入：无；所有文本都在字符串字面量中固定。
 * 输出：向标准输出写入多行文字；制表符的展开宽度依显示环境而异。
 * 标准：C99 或更新版本。
 */
#include <stdio.h> /* 引入 printf 的声明，供下方写出转义后的文本。 */

/*
 * 用途：按固定顺序打印若干转义序列的效果。
 * 参数：无；不读取启动参数或标准输入。
 * 返回值：int；返回 0 表示正常结束。
 * 错误处理：无输入要校验；本例不检查 printf 写出错误。
 * 副作用：向标准输出写多行文本。
 */
int main(void) {
    printf("line one\nline two\n"); /* 源码中的 \n 表示换行，让两段文字出现在不同输出行。 */
    printf("item\tcount\n"); /* \t 请求水平制表；实际对齐宽度依制表位和显示环境而异。 */
    printf("quote: \"C\"\n"); /* 字符串里的 \" 表示双引号字符，末尾 \n 再换行。 */
    printf("path: C:\\study\\demo.c\n"); /* 每个 \\ 在输出中产生一个反斜杠，避免误解为其他转义序列。 */
    return 0; /* 结束 main 并报告正常结束。 */
}

/* 示例输入：无。
 * 预期输出：
 * line one
 * line two
 * item<TAB>count（<TAB> 表示水平制表符，展开宽度依环境而异）
 * quote: "C"
 * path: C:\study\demo.c
 * 关键结果：转义序列在源码中表示特殊字符；输出呈现相应换行、制表或标点。
 */