/* =========================================================
 * 文件名：06_escape_chars.c
 * 描述：常用转义字符、八进制和十六进制转义示例
 * 注意：\\b 和 \\r 的实际显示效果会受终端影响。
 * ========================================================= */

/*
 * 文件用途：演示常见转义序列，以及八进制、十六进制字符常量。
 * 输入：无；转义序列均写在字符串或字符常量中。
 * 输出：标准输出显示转义符说明和对应字符；退格、回车的真实呈现依终端而异。
 */
#include <stdio.h>

/*
 * 用途：打印转义序列说明，并输出由八进制和十六进制转义表示的字符。
 * 参数：无；示例字符写在源码中。
 * 返回值：int；返回 0 表示正常结束。
 * 异常/错误：C 不使用异常机制；没有待校验输入；输出错误未检查，固定返回 0。
 * 副作用：向标准输出写入多行文本。
 * 复杂度：时间 O(1)，辅助空间 O(1)；输出语句数与示例长度固定。
 * 示例：运行本程序会执行多次 printf，并打印八进制 101 与十六进制 41 表示的字符。
 */
int main(void) {
    printf("===== 常用转义字符 =====\n");

    // \n 换行；\t 插入水平制表符。
    printf("1) \\n 换行：Hello\nWorld\n\n");
    printf("2) \\t 制表：A\tB\tC\tD\n");

    // 这里输出转义字符的书写形式，避免不同终端产生不一致的覆盖效果。
    printf("3) \\b 退格转义序列（实际效果依终端而定）\n");
    printf("4) \\r 回车转义序列（实际效果依终端而定）\n");

/*
 * 转义说明：源代码中的反斜杠负责引出转义序列；双反斜杠才会在输出中表示一个反斜杠字符。
 */
    // 在字符串中使用 \\ 表示一个反斜杠。
    printf("5) 反斜杠：project\\file.c\n");
    printf("6) \\' 单引号：'A'\n");
    printf("7) \\\" 双引号：\"Hello, World!\"\n");

    // \0 是空字符；在字符串中会作为结束标志，因此后面的 World 不会被 %s 输出。
    char truncated[] = "Hello\0World";
    printf("8) \\0 截断：\"Hello\\0World\" -> %s\n", truncated);
    putchar('\n');

/*
 * 数值说明：八进制形式（反斜杠后跟 101）与十六进制形式（反斜杠后跟 x41）都表示数值 65；十六进制转义会继续吸收紧随其后的十六进制数字。
 */
    // 八进制和十六进制转义都可以表示字符 'A'。
    printf("===== 八进制 / 十六进制转义 =====\n");
    printf("八进制 \\101 = %c\n", '\101');
    printf("十六进制 \\x41 = %c\n", '\x41');

    return 0;
}
