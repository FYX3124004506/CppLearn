/*
 * 文件用途：说明 C 关键字不能充当标识符，并对比可编译的普通变量名。
 * 输入：无；示例分数和通过标志由程序固定给出。
 * 输出：标准输出显示两个变量，并根据通过标志进入 if 分支。
 */
#include <stdio.h>

/*
 * 用途：运行合法的关键字命名对比示例；错误写法保持注释状态。
 * 参数：无；score 和 passed 在函数内赋固定初值。
 * 返回值：int；返回 0 表示正常结束。
 * 异常/错误：C 不使用异常机制；示例无输入；注释掉的错误声明不会编译，实际输出错误未检查。
 * 副作用：向标准输出写入变量值和通过提示。
 * 复杂度：时间 O(1)，辅助空间 O(1)；只有固定数量的判断和输出。
 * 示例：main 实际以 score=10、passed=1 调用 printf，并因 if (passed) 为真而调用第二次 printf。
 */
int main(void) {
    /*
     * 下面的名称都是 C 语言关键字，不能用作变量名。
     * 取消任意一行注释都会导致编译错误。
     */
    // int int = 10;
    // int if = 20;
    // int return = 30;

    // 正确做法：使用具有实际含义且不是关键字的名称。
/*
 * 关键变量：假设/待确认：score 的业务单位和通过标准未提供；当前值 10 仅为示例整数。passed 是逻辑标志，本例取 1 表示通过、0 表示不通过。
 */
    int score = 10;
    int passed = 1;

    printf("score = %d, passed = %d\n", score, passed);

    // 关键字可以作为 C 语言语法的一部分使用。
    if (passed) {
        printf("通过！\n");
    }

    return 0;
}
