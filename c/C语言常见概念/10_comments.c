/*
 * 文件用途：展示单行注释、块注释、行内注释，以及注释符作为字符串内容的情形。
 * 输入：无；注释本身不是运行时输入或执行语句。
 * 输出：标准输出显示 count 的计算结果和一行注释符文本。
 */
#include <stdio.h>

/*
 * 用途：修改局部变量并输出结果，同时用字符串展示注释符只是普通文本。
 * 参数：无；count 从函数内的固定值开始。
 * 返回值：int；返回 0 表示正常结束。
 * 异常/错误：C 不使用异常机制；无输入校验；printf 的写出错误未检查。
 * 副作用：把局部 count 从 2 增至 5，并向标准输出写入两行文本。
 * 复杂度：时间 O(1)，辅助空间 O(1)；没有随输入规模变化的操作。
 * 示例：运行 main 后 count 增加 3，再通过 printf 输出 count=5 和注释符文本。
 */
int main(void) {
    // 单行注释：说明当前变量的用途
    int count = 2;

    /* 块注释可以跨越多行，适合说明一段代码或较长的背景信息。 */
    count += 3; /* 行内块注释：说明这条表达式的作用 */

    printf("count = %d\n", count);

/*
 * 词法说明：编译器先识别字符串字面量；其中看起来像注释的字符只是字符串内容，不会开始或结束注释。
 */
    /* 注释符出现在字符串字面量中时只是普通字符。 */
    printf("// 和 /* */ 在字符串中只是文本\n");

    /*
     * 块注释不能嵌套。下面只是被行注释屏蔽的错误示意，
     * 不能取消行首的 // 后直接编译。
     */
    // /* 外层注释 /* 内层注释 */ 外层注释 */

    return 0;
}
